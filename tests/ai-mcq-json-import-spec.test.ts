import { describe, it, expect, beforeAll } from "vitest";
import {
  parseJSONWithLocation,
  processJSONImport,
  smartJSONImport,
  validateQuestion,
  normalizeQuestion,
  generateQuestionHash,
  escapeControlCharsInStrings,
  cleanTrailingCommas,
} from "../src/lib/mcqImport";
import { commitQuestions } from "../src/lib/mcqImport/commit";
import { isSupabaseConfigured, supabase } from "../src/lib/supabase";
import { setInMemoryProfile } from "../src/utils/userProfileStorage";

describe("DISHA 20-20 — AI MCQ Import JSON Format Specification Suite", () => {
  beforeAll(() => {
    setInMemoryProfile({
      id: "admin-spec-test",
      name: "Admin Tester",
      email: "jagdishpaliyaljat@gmail.com",
      role: "admin",
      status: "active",
      createdAt: new Date().toISOString(),
    });
  });
  const sampleCurriculum = {
    subjects: [
      { id: "sub_raj_hist", name: "Rajasthan History", hindiName: "राजस्थान का इतिहास" },
      { id: "sub_polity", name: "Indian Polity", hindiName: "भारतीय राजव्यवस्था" },
    ],
    chapters: [
      { id: "chap_panchayat", subjectId: "sub_polity", title: "Panchayati Raj", hindiTitle: "पंचायती राज" },
      { id: "chap_sources", subjectId: "sub_raj_hist", title: "Historical Sources", hindiTitle: "ऐतिहासिक स्रोत" },
    ],
    topics: [
      { id: "top_73rd", chapterId: "chap_panchayat", subjectId: "sub_polity", title: "73rd Amendment", hindiTitle: "73वां संविधान संशोधन" },
      { id: "top_inscriptions", chapterId: "chap_sources", subjectId: "sub_raj_hist", title: "Inscriptions", hindiTitle: "प्रमुख अभिलेख" },
    ],
  };

  // Task 1, 2, 3, 4: Exact JSON structure parsing
  it("Task 1-4: Supports exact required JSON structure and direct text parsing", async () => {
    const jsonInput = JSON.stringify({
      schemaVersion: 1,
      questions: [
        {
          type: "single_correct",
          question: "Question text",
          options: ["Option 1", "Option 2", "Option 3", "Option 4"],
          answer: "A",
          explanation: "Explanation",
          subject: "Subject",
          chapter: "Chapter",
          topic: "Topic",
        },
      ],
    });

    const parsed = await smartJSONImport(jsonInput, new Set(), { skipAIRecovery: true });
    expect(parsed.success).toBe(true);
    expect(parsed.results.length).toBe(1);

    const q = parsed.results[0];
    expect(q.isValid).toBe(true);
    expect(q.type).toBe("single_correct");
    expect(q.question).toBe("Question text");
    expect(q.options).toEqual(["Option 1", "Option 2", "Option 3", "Option 4"]);
    expect(q.answer).toBe("A");
    expect(q.correctIndex).toBe(0);
    expect(q.explanation).toBe("Explanation");
    expect(q.subject).toBe("Subject");
    expect(q.chapter).toBe("Chapter");
    expect(q.topic).toBe("Topic");
  });

  // Task 5: Support uploading .json files (parses clean JSON string)
  it("Task 5: Supports uploaded .json file string with UTF-8 BOM", () => {
    const rawFileContent = "\uFEFF" + JSON.stringify({
      schemaVersion: 1,
      questions: [
        {
          type: "single_correct",
          question: "राजस्थान का राज्य पक्षी कौन-सा है?",
          options: ["मोर", "गोडावण", "तोता", "कोयल"],
          answer: "B",
          explanation: "गोडावण राजस्थान का राज्य पक्षी है।",
          subject: "राजस्थान का इतिहास",
          chapter: "ऐतिहासिक स्रोत",
          topic: "प्रमुख अभिलेख",
        },
      ],
    });

    const { data, error } = parseJSONWithLocation(rawFileContent);
    expect(error).toBeUndefined();
    expect(data).toBeDefined();
    expect(data.schemaVersion).toBe(1);
    expect(data.questions.length).toBe(1);
    expect(data.questions[0].options[1]).toBe("गोडावण");
  });

  // Task 6: Support JSON inside markdown code fences (```json)
  it("Task 6: Extracts and parses JSON inside markdown code fences with prose", () => {
    const markdownInput = `
Here are the questions generated by AI:
\`\`\`json
{
  "schemaVersion": 1,
  "questions": [
    {
      "type": "single_correct",
      "question": "Which gas is most abundant in Earth's atmosphere?",
      "options": ["Oxygen", "Nitrogen", "Argon", "Carbon Dioxide"],
      "answer": "B",
      "explanation": "Nitrogen makes up roughly 78% of the atmosphere."
    }
  ]
}
\`\`\`
Hope this helps! Let me know if you need any adjustments.
`;

    const { data, error } = parseJSONWithLocation(markdownInput);
    expect(error).toBeUndefined();
    expect(data).toBeDefined();
    expect(data.schemaVersion).toBe(1);
    expect(data.questions.length).toBe(1);
    expect(data.questions[0].answer).toBe("B");
  });

  // Task 7: Support escaped newline characters and literal unescaped newlines
  it("Task 7: Handles escaped newlines and literal unescaped newlines in JSON strings", () => {
    // Literal unescaped newlines inside strings (common in AI outputs)
    const literalNewlines = `{
  "schemaVersion": 1,
  "questions": [
    {
      "type": "statement_based",
      "question": "कथन 1: पृथ्वी सूर्य का चक्कर लगाती है।
कथन 2: चंद्रमा पृथ्वी का उपग्रह है।",
      "options": ["केवल 1", "केवल 2", "1 और 2 दोनों", "कोई नहीं"],
      "answer": "C",
      "explanation": "दोनों कथन सत्य हैं।"
    }
  ]
}`;

    const { data, error } = parseJSONWithLocation(literalNewlines);
    expect(error).toBeUndefined();
    expect(data).toBeDefined();
    expect(data.questions[0].question).toContain("कथन 1");
    expect(data.questions[0].question).toContain("कथन 2");

    // Escaped newlines (\\n) in string
    const escapedNewlines = JSON.stringify({
      schemaVersion: 1,
      questions: [
        {
          type: "single_correct",
          question: "Line 1\\nLine 2\\nLine 3",
          options: ["A", "B", "C", "D"],
          answer: "A",
        },
      ],
    });

    const parsed = processJSONImport(escapedNewlines);
    expect(parsed.success).toBe(true);
    expect(parsed.results[0].question).toContain("\n");
  });

  // Task 8: Validate schemaVersion
  it("Task 8: Validates schemaVersion (accepts 1, rejects other versions)", async () => {
    const invalidVersionJson = JSON.stringify({
      schemaVersion: 2,
      questions: [
        {
          type: "single_correct",
          question: "Sample Question?",
          options: ["A", "B", "C", "D"],
          answer: "A",
        },
      ],
    });

    const res = await smartJSONImport(invalidVersionJson, new Set(), { skipAIRecovery: true });
    expect(res.success).toBe(false);
    expect(res.parseError).toContain("Unsupported schemaVersion");
  });

  // Task 9: Validate questions array
  it("Task 9: Validates questions array (rejects non-array and empty array)", async () => {
    // Non-array questions
    const notArrayJson = JSON.stringify({
      schemaVersion: 1,
      questions: "not an array",
    });
    const res1 = await smartJSONImport(notArrayJson, new Set(), { skipAIRecovery: true });
    expect(res1.success).toBe(false);
    expect(res1.parseError).toContain("'questions' must be an array");

    // Empty array
    const emptyArrayJson = JSON.stringify({
      schemaVersion: 1,
      questions: [],
    });
    const res2 = await smartJSONImport(emptyArrayJson, new Set(), { skipAIRecovery: true });
    expect(res2.success).toBe(false);
    expect(res2.parseError).toBeDefined();
  });

  // Task 10: Validate required question fields
  it("Task 10: Validates required question fields (question text, options, answer)", () => {
    const missingFieldsJson = JSON.stringify({
      schemaVersion: 1,
      questions: [
        {
          question: "", // missing text
          options: ["Opt 1", "Opt 2"],
          answer: "A",
        },
        {
          question: "Valid Question",
          options: [], // missing options
          answer: "A",
        },
        {
          question: "Valid Question",
          options: ["Opt 1", "Opt 2"],
          answer: "", // missing answer
        },
      ],
    });

    const parsed = processJSONImport(missingFieldsJson);
    expect(parsed.success).toBe(true);
    expect(parsed.results.length).toBe(3);

    // Q1 missing question text
    expect(parsed.results[0].isValid).toBe(false);
    expect(parsed.results[0].errors.some((e) => e.includes("Question text is missing"))).toBe(true);

    // Q2 missing options
    expect(parsed.results[1].isValid).toBe(false);
    expect(parsed.results[1].errors.some((e) => e.includes("at least 2 options"))).toBe(true);

    // Q3 missing answer
    expect(parsed.results[2].isValid).toBe(false);
    expect(parsed.results[2].errors.some((e) => e.includes("Correct answer is missing"))).toBe(true);
  });

  // Task 11: Validate options array (2-5 options)
  it("Task 11: Enforces options array count (2-5 options) and rejects empty option text", () => {
    const optionsCountJson = JSON.stringify({
      schemaVersion: 1,
      questions: [
        {
          question: "Question with only 1 option?",
          options: ["Only Option"],
          answer: "A",
        },
        {
          question: "Question with 6 options?",
          options: ["Opt 1", "Opt 2", "Opt 3", "Opt 4", "Opt 5", "Opt 6"],
          answer: "A",
        },
        {
          question: "Question with empty option text?",
          options: ["Opt A", "   ", "Opt C", "Opt D"],
          answer: "A",
        },
      ],
    });

    const parsed = processJSONImport(optionsCountJson);
    expect(parsed.success).toBe(true);
    expect(parsed.results[0].isValid).toBe(false);
    expect(parsed.results[0].errors.some((e) => e.includes("at least 2 options"))).toBe(true);

    expect(parsed.results[1].isValid).toBe(false);
    expect(parsed.results[1].errors.some((e) => e.includes("more than 5 options"))).toBe(true);

    expect(parsed.results[2].isValid).toBe(false);
    expect(parsed.results[2].errors.some((e) => e.includes("Option B text is empty"))).toBe(true);
  });

  // Task 12: Validate answer against option position
  it("Task 12: Validates answer against option position (out of bounds and invalid answers)", () => {
    const answerOutOfBoundsJson = JSON.stringify({
      schemaVersion: 1,
      questions: [
        {
          question: "Question with 4 options but answer E?",
          options: ["Opt A", "Opt B", "Opt C", "Opt D"],
          answer: "E", // 4 options -> valid: A-D (0-3)
        },
        {
          question: "Question with invalid answer letter Z?",
          options: ["Opt A", "Opt B", "Opt C", "Opt D"],
          answer: "Z",
        },
      ],
    });

    const parsed = processJSONImport(answerOutOfBoundsJson);
    expect(parsed.success).toBe(true);
    expect(parsed.results[0].isValid).toBe(false);
    expect(parsed.results[0].errors.some((e) => e.includes("exceeds available options count"))).toBe(true);

    expect(parsed.results[1].isValid).toBe(false);
    expect(parsed.results[1].errors.some((e) => e.includes("does not match A–E"))).toBe(true);
  });

  // Task 13: Support all question types: single_correct, statement_based, assertion_reason, match_list, math
  it("Task 13: Supports all 5 question types cleanly", () => {
    const allTypes = [
      {
        type: "single_correct",
        question: "Single correct question?",
        options: ["A", "B", "C", "D"],
        answer: "A",
      },
      {
        type: "statement_based",
        question: "Statement question:\n1. Statement One\n2. Statement Two",
        statements: ["Statement One", "Statement Two"],
        options: ["Only 1", "Only 2", "Both 1 and 2", "Neither"],
        answer: "C",
      },
      {
        type: "assertion_reason",
        question: "Assertion (A): Sun rises in the east.\nReason (R): Earth rotates from west to east.",
        assertion: "Sun rises in the east.",
        reason: "Earth rotates from west to east.",
        options: ["Both A and R true, R explains A", "Both true, R does not explain A", "A true R false", "A false R true"],
        answer: "A",
      },
      {
        type: "match_list",
        question: "Match List-I with List-II:\nA. Item 1\nB. Item 2",
        matchTable: {
          leftTitle: "List-I",
          rightTitle: "List-II",
          rows: [
            { left: "Item 1", right: "Match 1" },
            { left: "Item 2", right: "Match 2" },
          ],
        },
        options: ["A-1, B-2", "A-2, B-1", "A-1, B-1", "A-2, B-2"],
        answer: "A",
      },
      {
        type: "math",
        question: "If $f(x) = 2x + 3$, what is $f(4)$?",
        options: ["10", "11", "12", "14"],
        answer: "B",
        explanation: "$f(4) = 2(4) + 3 = 8 + 3 = 11$.",
      },
    ];

    allTypes.forEach((rawQ, i) => {
      const norm = normalizeQuestion(rawQ);
      const val = validateQuestion(norm, i + 1);

      expect(val.isValid).toBe(true);
      expect(norm.type).toBe(rawQ.type);
      expect(val.reviewCategory).not.toBe("unsupported");
    });
  });

  // Task 14: Validate subject, chapter and topic mapping
  it("Task 14: Validates subject, chapter, and topic mapping against curriculum", () => {
    const qWithValidCurriculum = {
      type: "single_correct",
      question: "73वां संविधान संशोधन किससे संबंधित है?",
      options: ["नगरपालिका", "पंचायती राज", "सहकारी समितियां", "वित्त आयोग"],
      answer: "B",
      subject: "भारतीय राजव्यवस्था",
      chapter: "पंचायती राज",
      topic: "73वां संविधान संशोधन",
    };

    const norm = normalizeQuestion(qWithValidCurriculum);
    const valValid = validateQuestion(norm, 1, { curriculum: sampleCurriculum });
    expect(valValid.isValid).toBe(true);
    // Should have no unmapped warnings for curriculum
    expect(valValid.warnings.some((w) => w.includes("could not be mapped"))).toBe(false);

    const qWithUnmappedCurriculum = {
      type: "single_correct",
      question: "Sample unmapped question?",
      options: ["A", "B", "C", "D"],
      answer: "A",
      subject: "NonExistentSubject123",
      chapter: "NonExistentChapter123",
      topic: "NonExistentTopic123",
    };

    const normUnmapped = normalizeQuestion(qWithUnmappedCurriculum);
    const valUnmapped = validateQuestion(normUnmapped, 2, { curriculum: sampleCurriculum });
    expect(valUnmapped.warnings.some((w) => w.includes("Subject \"NonExistentSubject123\" could not be mapped"))).toBe(true);
    expect(valUnmapped.warnings.some((w) => w.includes("Chapter \"NonExistentChapter123\" could not be mapped"))).toBe(true);
    expect(valUnmapped.warnings.some((w) => w.includes("Topic \"NonExistentTopic123\" could not be mapped"))).toBe(true);
  });

  // Task 15: Support Hindi and English Unicode text
  it("Task 15: Preserves full Devanagari Hindi and English Unicode text", () => {
    const hindiJson = JSON.stringify({
      schemaVersion: 1,
      questions: [
        {
          type: "single_correct",
          question: "हल्दीघाटी का ऐतिहासिक युद्ध कब लड़ा गया था? (Battle of Haldighati)",
          options: ["18 जून 1576", "1527 ई.", "1191 ई.", "1192 ई."],
          answer: "A",
          explanation: "हल्दीघाटी का युद्ध 18 जून 1576 को महाराणा प्रताप और अकबर की सेना के मध्य लड़ा गया था।",
          subject: "राजस्थान का इतिहास",
          chapter: "ऐतिहासिक स्रोत",
          topic: "प्रमुख अभिलेख",
        },
      ],
    });

    const parsed = processJSONImport(hindiJson);
    expect(parsed.success).toBe(true);
    const q = parsed.results[0];
    expect(q.isValid).toBe(true);
    expect(q.question).toBe("हल्दीघाटी का ऐतिहासिक युद्ध कब लड़ा गया था? (Battle of Haldighati)");
    expect(q.options[0]).toBe("18 जून 1576");
    expect(q.explanation).toContain("महाराणा प्रताप");
  });

  // Task 16: Display validation errors with question index
  it("Task 16: Formats validation errors with question index (e.g. Q1, Q2)", () => {
    const invalidBatch = JSON.stringify({
      schemaVersion: 1,
      questions: [
        {
          question: "",
          options: ["A", "B"],
          answer: "A",
        },
        {
          question: "Valid Question",
          options: ["A", "B"],
          answer: "Z",
        },
      ],
    });

    const parsed = processJSONImport(invalidBatch);
    expect(parsed.results[0].errors[0]).toMatch(/^Q1:/);
    expect(parsed.results[1].errors[0]).toMatch(/^Q2:/);
  });

  // Task 17: Show preview before importing (summary and structured results)
  it("Task 17: Generates structured preview summary before importing", () => {
    const batchJson = JSON.stringify({
      schemaVersion: 1,
      questions: [
        {
          question: "Valid Q1?",
          options: ["A", "B", "C", "D"],
          answer: "A",
        },
        {
          question: "", // invalid
          options: ["A", "B"],
          answer: "A",
        },
      ],
    });

    const parsed = processJSONImport(batchJson);
    expect(parsed.success).toBe(true);
    expect(parsed.summary.total).toBe(2);
    expect(parsed.summary.valid).toBe(1);
    expect(parsed.summary.errors).toBe(1);
    expect(parsed.results.length).toBe(2);
  });

  // Task 18, 19, 20: Prevent duplicate MCQ insertion and verify Supabase actual insertion
  it("Task 18-20: Prevents duplicate insertion and enforces strict Supabase confirmation rule", async () => {
    const q1 = normalizeQuestion({
      type: "single_correct",
      question: "Duplicate test question for Disha2020 verification?",
      options: ["Option A", "Option B", "Option C", "Option D"],
      answer: "A",
    });

    const hash1 = generateQuestionHash(q1);
    expect(hash1).toBeDefined();
    expect(typeof hash1).toBe("string");

    // In-batch duplicate detection
    const dupeJson = JSON.stringify({
      schemaVersion: 1,
      questions: [
        {
          question: "Duplicate question stem for testing?",
          options: ["Opt 1", "Opt 2", "Opt 3", "Opt 4"],
          answer: "A",
        },
        {
          question: "Duplicate question stem for testing?",
          options: ["Opt 1", "Opt 2", "Opt 3", "Opt 4"],
          answer: "A",
        },
      ],
    });

    const parsed = processJSONImport(dupeJson);
    expect(parsed.results[0].isDuplicate).toBe(false);
    expect(parsed.results[1].isDuplicate).toBe(true);
    expect(parsed.summary.duplicates).toBe(1);

    // Rule: "Do not show success before Supabase confirms insertion."
    // In unauthenticated context, Supabase RLS denies insertion, so commitQuestions MUST NOT return success=true
    if (isSupabaseConfigured()) {
      const testQuestion = {
        id: `usr-q-top_inscriptions-spec_test_${Date.now()}`,
        text: "DISHA2020 Spec Test Question Insertion?",
        options: ["Option 1", "Option 2", "Option 3", "Option 4"] as [string, string, string, string],
        correctIndex: 0,
        explanation: "Insertion test without confirmed admin JWT.",
        subjectId: "sub_raj_hist",
        chapterId: "chap_raj_sources",
        topicId: "top_inscriptions",
        questionType: "single_correct",
        createdAt: new Date().toISOString(),
        isUserAdded: true,
      };

      const commitRes = await commitQuestions([testQuestion as any], `spec_batch_${Date.now()}`);
      // Supabase RLS blocks anon write with 42501, so commitRes.success must be false
      // and must never report false success!
      expect(commitRes.success).toBe(false);
      expect(commitRes.error).toBeDefined();
      expect(commitRes.error?.toLowerCase()).toContain("sign in with admin");
    }
  });
});
